"""Verify and stage a signed release. Does not upload, deploy or modify a database."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import struct
import zipfile

ROOT = Path(__file__).resolve().parents[1]

def run(*args):
    completed = subprocess.run([str(a) for a in args], check=True, capture_output=True, text=True)
    return completed.stdout + completed.stderr

def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apk', type=Path, default=ROOT / 'app/build/outputs/apk/release/app-release.apk')
    parser.add_argument('--previous-apk', type=Path, required=True, help='Previously published APK, for signing-key continuity')
    parser.add_argument('--notes', default='Reliable downloads, phone-aware recommendations, multilingual fixes, and optional app updates.')
    args = parser.parse_args()
    sdk = Path(os.environ['ANDROID_HOME'])
    build_tools = sorted((sdk / 'build-tools').iterdir(), key=lambda p: tuple(int(x) for x in p.name.split('.') if x.isdigit()))[-1]
    ext = '.bat' if os.name == 'nt' else ''
    signer = build_tools / ('apksigner' + ext)
    def cert(apk):
        result = run(signer, 'verify', '--verbose', '--print-certs', apk)
        match = re.search(r'Signer #1 certificate SHA-256 digest: ([a-f0-9]+)', result)
        if not match: raise ValueError('APK signing certificate could not be verified')
        return match.group(1)
    assert cert(args.apk) == cert(args.previous_apk), 'Signing key changed; existing installations cannot update'
    aapt = build_tools / ('aapt.exe' if os.name == 'nt' else 'aapt')
    badging = run(aapt, 'dump', 'badging', args.apk)
    assert "package: name='app.llmobi'" in badging
    assert 'application-debuggable' not in badging
    code = int(re.search(r"versionCode='(\d+)'", badging).group(1))
    name = re.search(r"versionName='([^']+)'", badging).group(1)
    assert re.fullmatch(r'\d+\.\d+\.\d+', name)
    old_code = int(re.search(r"versionCode='(\d+)'", run(aapt, 'dump', 'badging', args.previous_apk)).group(1))
    assert code > old_code, 'Release version must increase'
    minimum = int(re.search(r"sdkVersion:'(\d+)'", badging).group(1))
    run(build_tools / ('zipalign.exe' if os.name == 'nt' else 'zipalign'), '-c', '-P', '16', '4', args.apk)
    with zipfile.ZipFile(args.apk) as archive:
        assert archive.testzip() is None, 'APK archive is damaged'
        assert 'lib/arm64-v8a/libllmobi.so' in archive.namelist(), 'Native inference engine missing'
        for library in (n for n in archive.namelist() if n.startswith('lib/') and n.endswith('.so')):
            elf = archive.read(library)
            assert elf[:6] == b'\x7fELF\x02\x01', f'Expected a 64-bit little-endian ELF: {library}'
            phoff = struct.unpack_from('<Q', elf, 32)[0]
            entry_size, count = struct.unpack_from('<HH', elf, 54)
            for i in range(count):
                kind, _, offset, address, _, _, _, alignment = struct.unpack_from('<IIQQQQQQ', elf, phoff + i * entry_size)
                if kind == 1:  # PT_LOAD, checked independently from APK ZIP alignment
                    assert alignment >= 16384 and offset % 16384 == address % 16384, f'16 KB ELF alignment failed: {library}'
    sha = digest(args.apk)
    info = dict(versionCode=code, versionName=name, url=f'https://llmobi.pages.dev/releases/llmobi-{name}.apk',
                bytes=args.apk.stat().st_size, sha256=sha, minSdk=minimum, notes=args.notes)
    dest = ROOT / f'web/public/releases/llmobi-{name}.apk'
    if dest.exists() and digest(dest) != sha:
        raise ValueError('That immutable release filename already contains different bytes; use a new version')
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(args.apk, dest)
    shutil.copy2(args.apk, ROOT / 'web/public/llmobi.apk')
    (ROOT / 'api/src/release.js').write_text('// Generated by tools/prepare_release.py. Publish the APK before this manifest.\nexport const RELEASE = ' + json.dumps(info, indent=2) + '\n', encoding='utf-8')
    evidence = ROOT / f'release-artifacts/{name}'
    evidence.mkdir(parents=True, exist_ok=True)
    (evidence / 'release.json').write_text(json.dumps(info, indent=2) + '\n', encoding='utf-8')
    (evidence / 'SHA256SUMS').write_text(f'{sha}  llmobi-{name}.apk\n', encoding='utf-8')
    print(json.dumps(info, indent=2))

if __name__ == '__main__':
    main()
